// Stages the GitHub Pages site from the single-file release (run after `npm run release`): site/index.html plus
// what makes the online build installable as a desktop app in Chrome and Edge (Brandon, 2026-11-12): a web app
// manifest, the icons from assets/app/ and a small service worker. The game itself stays one self-contained file;
// these extra files only exist on the Pages site, and src/ui/install.ts does nothing where they are missing.
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadTs } from './load-ts.mjs';

const SITE = process.argv[2] ?? 'site';
const { APP_ICONS, MANIFEST_FILE, SERVICE_WORKER_FILE, buildManifest } = await loadTs('src/app/app-shell.ts');
const manifest = buildManifest();

rmSync(SITE, { recursive: true, force: true });
mkdirSync(join(SITE, 'icons'), { recursive: true });
for (const i of APP_ICONS) copyFileSync(join('assets/app', i.file), join(SITE, 'icons', i.file));
writeFileSync(join(SITE, MANIFEST_FILE), JSON.stringify(manifest, null, 2));

const head = [
  `<link rel="manifest" href="${MANIFEST_FILE}" />`,
  `<meta name="theme-color" content="${manifest.theme_color}" />`,
  `<link rel="icon" type="image/png" sizes="192x192" href="icons/icon-192.png" />`,
  `<link rel="apple-touch-icon" href="icons/icon-192.png" />`,
].join('\n    ');
const html = readFileSync('release/index.html', 'utf8');
if (!html.includes('</head>')) throw new Error('stage-pages: release/index.html has no </head>');
writeFileSync(join(SITE, 'index.html'), html.replace('</head>', () => `    ${head}\n  </head>`));

// The service worker makes the site installable and lets the app open offline. Network first, so a new build is
// always picked up when online; the last good copy of the game is the fallback when the network is down.
const build = JSON.parse(readFileSync('package.json', 'utf8')).version;
writeFileSync(join(SITE, SERVICE_WORKER_FILE), `// BIOPHAGE app shell, build ${build}. Generated by scripts/stage-pages.mjs.
const CACHE = 'biophage-shell';
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (e) => e.waitUntil(self.clients.claim()));
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(fetch(req).then((res) => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return res;
  }).catch(() => caches.match(req).then((hit) => hit || (req.mode === 'navigate' ? caches.match('./') : undefined)).then((hit) => hit || Response.error())));
});
`);
writeFileSync(join(SITE, '.nojekyll'), '');
console.log(`stage-pages: ${SITE}/ (index.html, ${MANIFEST_FILE}, ${SERVICE_WORKER_FILE}, ${APP_ICONS.length} icons)`);
